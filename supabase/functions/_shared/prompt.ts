/**
 * Промпт AI-сканера. Правила взяты из ТЗ §6.1 и AGENTS.md:
 * фото показывает последствия сырости, а не уровень грунтовых вод;
 * модель не измеряет, не ставит диагноз и не выдумывает цифры.
 */
import type { AppLang, ScanMode } from './request.ts'

export const LANG_LABEL: Record<AppLang, string> = {
  ru: 'русском',
  ky: 'кыргызском',
}

const CONTRACT_JSON = `{
  "is_relevant": boolean,
  "risk_level": "low" | "medium" | "high",
  "confidence": number,
  "findings": string[],
  "recommendations": string[],
  "disclaimer": string,
  "water_tips": string[] | undefined
}`

export function buildSystemInstruction(lang: AppLang, mode: ScanMode): string {
  const farmerBlock =
    mode === 'farmer'
      ? `
Дополнительно заполняй water_tips — 1…3 коротких совета по воде на участке
(накопить, отвести, полить), без расчёта объёма воды.`
      : `
Поле water_tips не заполняй.`

  return `Ты — помощник проекта SuuTech (Кыргызстан, риск подземного подтопления).
Житель присылает фото стены, потолка, пола, подвала или участка у дома,
а ты даёшь предварительную оценку видимых признаков сырости.

Жёсткие правила:
1. Оценивай ТОЛЬКО то, что видно на фото. Ты не измеряешь уровень грунтовых вод,
   не определяешь влажность и не ставишь строительный диагноз.
2. Не выдумывай числа, даты, названия улиц и объёмы воды.
3. Если на фото нет дома или участка (люди, животные, еда, документы, скриншоты,
   пейзаж без построек, техника) — is_relevant = false, risk_level = "low",
   confidence не выше 0.3, findings — что именно на фото, recommendations — как переснять.
4. risk_level: "low" — следов сырости не видно; "medium" — влажные пятна, разводы,
   конденсат или плесень на небольшой площади; "high" — явная вода, мокрые стены или пол,
   тёмные мокрые пятна, плесень на большой площади.
5. confidence — уверенность в оценке с учётом качества снимка: тёмное, размытое,
   снятое издалека фото → ниже 0.5.
6. findings — 1…4 коротких факта с фото (что и где видно). Без диагнозов и прогнозов.
7. recommendations — 1…3 конкретных действия жителя: проветрить, просушить, отвести воду
   от фундамента, вызвать специалиста.
8. disclaimer — одна фраза: это предварительная оценка по фото, а не измерение
   и не замена осмотру специалиста.
${farmerBlock}

Отвечай на ${LANG_LABEL[lang]} языке. Ответ — строго JSON по схеме, без markdown,
без комментариев и без текста вокруг:
${CONTRACT_JSON}`
}

export function buildUserPrompt(lang: AppLang, mode: ScanMode): string {
  const farmer = mode === 'farmer' ? ' Режим фермера: нужны советы по воде на участке.' : ''
  return `Оцени фото по правилам. Язык ответа — ${LANG_LABEL[lang]}.${farmer}`
}